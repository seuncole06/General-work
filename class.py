class Student:
    def __init__(self, name, age):
        self.name = name
        self.age = age

Student1 = Student("seun", 23)
Student2 = Student("daniel", 50)
Student3 = Student("cole", 70)

print(Student1.name)
print(Student1.age)

print(Student2.name)
print(Student2.age)

print(Student3.name)
print(Student3.age)

